const fs = require("node:fs");

const pokemon = JSON.parse(fs.readFileSync("pokemon.json", "utf8"));
const cpMultipliers = JSON.parse(fs.readFileSync("cp-multipliers.json", "utf8"));
const names = parseCsv(fs.readFileSync("names.csv", "utf8"));
const namesByPokemonId = Object.fromEntries(pokemon.map(([pokemonId, number]) => {
  const translatedNames = names[number - 1];

  if (!translatedNames) {
    throw new Error(`Missing translated names for Pokédex number ${number}.`);
  }

  return [pokemonId, {
    csvId: translatedNames.key,
    en: translatedNames.en,
    de: translatedNames.de,
    ja: translatedNames.ja
  }];
}));
const contents = [
  "// Generated by generate-offline-data.js. Do not edit directly.",
  `window.POGO_OFFLINE_DATA=${JSON.stringify({ pokemon, cpMultipliers, names: namesByPokemonId })};`,
  ""
].join("\n");

fs.writeFileSync("offline-data.js", contents);

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;

  for (let index = 0; index < text.length; index += 1) {
    const character = text[index];

    if (quoted) {
      if (character === '"' && text[index + 1] === '"') {
        field += '"';
        index += 1;
      } else if (character === '"') {
        quoted = false;
      } else {
        field += character;
      }
    } else if (character === '"') {
      quoted = true;
    } else if (character === ",") {
      row.push(field);
      field = "";
    } else if (character === "\n") {
      row.push(field.replace(/\r$/, ""));
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += character;
    }
  }

  if (field || row.length) {
    row.push(field.replace(/\r$/, ""));
    rows.push(row);
  }

  const headers = rows.shift();
  return rows
    .filter((values) => values.some(Boolean))
    .map((values) => Object.fromEntries(headers.map((header, index) => [header, values[index] || ""])));
}
